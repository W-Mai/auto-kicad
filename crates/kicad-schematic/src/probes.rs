use sha2::{Digest, Sha256};
use std::{
    collections::{BTreeMap, BTreeSet},
    path::Path,
};

#[derive(Clone, Debug, Eq, PartialEq, Ord, PartialOrd)]
pub enum ConnectivityPin {
    Component(LogicalPinKey),
    Virtual {
        source: SourceUnitKey,
        number: String,
    },
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ConnectivityNet {
    pub name: String,
    pub class: Option<String>,
    pub pins: Vec<ConnectivityPin>,
}

/// Baseline ERC and marker evidence remain on the original audit, not on probe reports.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct PinConnectivity {
    nets: Vec<ConnectivityNet>,
    isolated_no_connect: Vec<ConnectivityPin>,
}
impl PinConnectivity {
    pub fn nets(&self) -> &[ConnectivityNet] {
        &self.nets
    }
    pub fn isolated_no_connect(&self) -> &[ConnectivityPin] {
        &self.isolated_no_connect
    }
    pub fn partitions(&self) -> Vec<Vec<ConnectivityPin>> {
        let mut groups = self.nets.iter().map(|n| n.pins.clone()).collect::<Vec<_>>();
        groups.sort();
        groups
    }
}

/// Generated bytes are private native witnesses; this type grants no publication authority.
pub struct PinProbePlan {
    files: BTreeMap<String, Vec<u8>>,
    candidate: ParsedSchematicProject,
    original: NetlistDocument,
    pins: SchematicPinIndex,
    probes: BTreeMap<String, Vec<ConnectivityPin>>,
    isolated: Vec<ConnectivityPin>,
    prefix: String,
}

fn quote(value: &str) -> String {
    let mut text = String::from("\"");
    for c in value.chars() {
        match c {
            '\\' => text.push_str("\\\\"),
            '"' => text.push_str("\\\""),
            '\n' => text.push_str("\\n"),
            '\r' => text.push_str("\\r"),
            '\t' => text.push_str("\\t"),
            _ => text.push(c),
        }
    }
    text.push('"');
    text
}
fn private_uuid(seed: &str, index: usize) -> String {
    let mut bytes = Sha256::digest(format!("{seed}:{index}"));
    bytes[6] = (bytes[6] & 15) | 64;
    bytes[8] = (bytes[8] & 63) | 128;
    let s = hex::encode(&bytes[..16]);
    format!(
        "{}-{}-{}-{}-{}",
        &s[..8],
        &s[8..12],
        &s[12..16],
        &s[16..20],
        &s[20..]
    )
}
fn children<'a>(items: &'a [Node], name: &'a str) -> impl Iterator<Item = &'a Node> {
    items
        .iter()
        .filter(move |n| list_items(n).is_some_and(|n| list_tag(n) == Some(name)))
}
fn has_jumpers(nodes: &[Node]) -> bool {
    let mut pending = nodes.iter().collect::<Vec<_>>();
    while let Some(node) = pending.pop() {
        if let Some(items) = list_items(node) {
            if list_tag(items).is_some_and(|tag| tag.contains("jumper")) {
                return true;
            }
            pending.extend(items);
        }
    }
    false
}
const FONT: &str = "(effects (font (size 1.27 1.27)))";
fn property(name: &str, value: &str) -> String {
    format!(
        "(property {} {} (at 0 0 0) {FONT})",
        quote(name),
        quote(value)
    )
}

impl PinProbePlan {
    pub fn files(&self) -> &BTreeMap<String, Vec<u8>> {
        &self.files
    }
    pub fn probe_count(&self) -> usize {
        self.probes.len()
    }

    pub fn prepare(
        project: &ParsedSchematicProject,
        native: &NetlistDocument,
        sources: &BTreeMap<String, &[u8]>,
    ) -> Result<Self, String> {
        let pins = SchematicPinIndex::resolve(project, native, sources)?;
        if pins.unexported().len() > 100_000 {
            return Err("virtual probe count exceeds bound".into());
        }
        let seed = project.revision.digest.as_str();
        let prefix = format!(
            "AKOBS{}",
            seed.bytes()
                .take(24)
                .map(|c| char::from(b'a' + c % 16))
                .collect::<String>()
        );
        let occupied = |value: &str| {
            sources
                .values()
                .any(|s| s.windows(value.len()).any(|w| w == value.as_bytes()))
        };
        if occupied(&prefix) {
            return Err("private probe namespace collides with source text".into());
        }
        let mut reserved_uuids = BTreeSet::new();
        for bytes in sources.values() {
            let doc = parse_one(std::str::from_utf8(bytes).map_err(|e| e.to_string())?)
                .map_err(|e| e.to_string())?;
            let mut pending = doc.nodes.iter().collect::<Vec<_>>();
            while let Some(node) = pending.pop() {
                if let Some(items) = list_items(node) {
                    pending.extend(items);
                } else if let Some(atom) = crate::atom_text(Some(node))
                    && atom.len() == 36
                {
                    let normalized = atom.to_ascii_lowercase();
                    if crate::identities::uuid(&normalized) {
                        reserved_uuids.insert(normalized);
                    }
                }
            }
        }
        let project_name = Path::new(&project.root_relative_path)
            .file_stem()
            .and_then(|s| s.to_str())
            .ok_or("invalid probe project name")?;
        let library = format!("{prefix}:Contact");
        let mut physical = BTreeMap::new();
        let mut isolated = Vec::new();
        let mut keys = BTreeSet::new();
        for pin in pins.unexported() {
            if !pin.reference.starts_with('#') {
                return Err("unexported non-virtual source requires separate evidence".into());
            }
            let key = ConnectivityPin::Virtual {
                source: pin.occurrence.source.clone(),
                number: pin.number.clone(),
            };
            if !keys.insert(key.clone()) {
                return Err("ambiguous duplicate virtual logical contact".into());
            }
            if pin.occurrence.electrical_type == "no_connect" {
                isolated.push(key);
                continue;
            }
            let contact = (
                &pin.occurrence.source.file,
                &pin.occurrence.source.symbol_uuid,
                &pin.occurrence.graphical_number,
                pin.occurrence.position,
            );
            physical
                .entry(contact)
                .or_insert_with(Vec::new)
                .push((pin, key));
        }
        let mut probes = BTreeMap::new();
        let mut insertions = BTreeMap::<String, String>::new();
        let mut id_set = BTreeSet::new();
        for (ordinal, ((file, _, _, position), contacts)) in physical.into_iter().enumerate() {
            let id = private_uuid(seed, ordinal * 2);
            let pin_id = private_uuid(seed, ordinal * 2 + 1);
            if reserved_uuids.contains(&id)
                || reserved_uuids.contains(&pin_id)
                || !id_set.insert(id.clone())
                || !id_set.insert(pin_id.clone())
            {
                return Err("private probe UUID collision".into());
            }
            let mut instances = BTreeMap::<&str, Vec<ConnectivityPin>>::new();
            for (pin, key) in contacts {
                instances
                    .entry(&pin.occurrence.source.sheet_path)
                    .or_default()
                    .push(key);
            }
            let mut paths = String::new();
            let mut display = None;
            for (path, mut keys) in instances {
                keys.sort();
                let reference = format!("{prefix}{}", probes.len() + 1);
                display.get_or_insert_with(|| reference.clone());
                paths.push_str(&format!(
                    "(path {} (reference {}) (unit 1))",
                    quote(path),
                    quote(&reference)
                ));
                probes.insert(reference, keys);
            }
            let placed = format!(
                "(symbol (lib_id {}) (at {} {} 0) (unit 1) (in_bom no) (on_board no) (dnp no) (uuid {}) {} {} (pin \"1\" (uuid {})) (instances (project {} {})))",
                quote(&library),
                position.x.mm(),
                position.y.mm(),
                quote(&id),
                property(
                    "Reference",
                    display.as_deref().ok_or("empty probe instances")?
                ),
                property("Value", "Contact"),
                quote(&pin_id),
                quote(project_name),
                paths
            );
            insertions
                .entry(file.clone())
                .or_default()
                .push_str(&placed);
        }
        let definition = format!(
            "(symbol {} (in_bom no) (on_board no) {} {} (symbol \"Contact_1_1\" (pin passive line (at 0 0 0) (length 0) (name \"\" {FONT}) (number \"1\" {FONT}))))",
            quote(&library),
            property("Reference", "AKOBS"),
            property("Value", "Contact")
        );
        let mut files = BTreeMap::new();
        let mut parsed = Vec::new();
        let mut total = 0;
        for file in &project.files {
            let name = &file.artifact.relative_path;
            let original = std::str::from_utf8(sources[name]).map_err(|e| e.to_string())?;
            let doc = parse_one(original).map_err(|e| e.to_string())?;
            let root = list_items(&doc.nodes[0]).ok_or("invalid probe source root")?;
            if !isolated.is_empty() && has_jumpers(&doc.nodes) {
                return Err(
                    "virtual electrical-no-connect isolation with jumper definitions is unproven"
                        .into(),
                );
            }
            let mut candidate = original.to_owned();
            if let Some(symbols) = insertions.get(name) {
                let libraries = children(root, "lib_symbols").collect::<Vec<_>>();
                if libraries.len() != 1 {
                    return Err("ambiguous probe library insertion".into());
                }
                let library_end = node_span(libraries[0]).end;
                let root_end = node_span(&doc.nodes[0]).end;
                if library_end >= root_end
                    || original.as_bytes()[library_end - 1] != b')'
                    || original.as_bytes()[root_end - 1] != b')'
                {
                    return Err("invalid probe insertion spans".into());
                }
                candidate.insert_str(root_end - 1, &format!("\n{symbols}\n"));
                candidate.insert_str(library_end - 1, &format!("\n{definition}\n"));
            }
            total += candidate.len();
            if candidate.len() > 32 * 1024 * 1024 || total > 128 * 1024 * 1024 {
                return Err("private probe source exceeds byte bound".into());
            }
            parsed.push(parse_schematic(name, candidate.as_bytes()).map_err(|e| e.to_string())?);
            files.insert(name.clone(), candidate.into_bytes());
        }
        let revision = SchematicArtifactRevision::new(
            parsed.iter().map(|f| f.artifact.clone()).collect(),
            &project.revision.kicad_cli_version,
            project.revision.extractor_schema_version,
            project.editor_lock_present,
        )
        .map_err(|e| e.to_string())?;
        let candidate = ParsedSchematicProject {
            root_relative_path: project.root_relative_path.clone(),
            files: parsed,
            revision,
            editor_lock_present: project.editor_lock_present,
        };
        isolated.sort();
        Ok(Self {
            files,
            candidate,
            original: native.clone(),
            pins,
            probes,
            isolated,
            prefix,
        })
    }

    pub fn validate(&self, witness: &NetlistDocument) -> Result<PinConnectivity, String> {
        let sources = self
            .files
            .iter()
            .map(|(p, b)| (p.clone(), b.as_slice()))
            .collect();
        let observed = SchematicPinIndex::resolve(&self.candidate, witness, &sources)?;
        if observed.unexported() != self.pins.unexported()
            || witness.sheets != self.original.sheets
            || witness.export_version != self.original.export_version
        {
            return Err("probe changed source identity or hierarchy evidence".into());
        }
        let components = witness
            .components
            .iter()
            .map(|c| (&c.reference, c))
            .collect::<BTreeMap<_, _>>();
        for original in &self.original.components {
            if components.get(&original.reference).copied() != Some(original) {
                return Err("probe changed original component evidence".into());
            }
        }
        if components.len() != self.original.components.len() + self.probes.len() {
            return Err("unexpected probe component set".into());
        }
        let baseline = self
            .pins
            .pins()
            .iter()
            .map(|p| (&p.key, p))
            .collect::<BTreeMap<_, _>>();
        let mut projected = BTreeMap::<&str, Vec<LogicalPinKey>>::new();
        let mut groups = BTreeMap::<&str, ConnectivityNet>::new();
        let mut seen_probes = BTreeSet::new();
        let mut seen_original = BTreeSet::new();
        for pin in observed.pins() {
            let keys = if let Some(original) = baseline.get(&pin.key) {
                if pin.net.name != original.net.name
                    || pin.net.class != original.net.class
                    || pin.net.pin_function != original.net.pin_function
                    || pin.net.electrical_type != original.net.electrical_type
                    || pin.occurrences != original.occurrences
                    || pin.reference != original.reference
                {
                    return Err("probe changed original pin or network metadata".into());
                }
                projected
                    .entry(&pin.net.code)
                    .or_default()
                    .push(pin.key.clone());
                seen_original.insert(&pin.key);
                vec![ConnectivityPin::Component(pin.key.clone())]
            } else if let Some(keys) = self.probes.get(&pin.reference) {
                if pin.key.number != "1"
                    || pin.net.electrical_type != "passive"
                    || !pin.net.pin_function.is_empty()
                    || !seen_probes.insert(&pin.reference)
                {
                    return Err("invalid or repeated passive probe node".into());
                }
                keys.clone()
            } else {
                return Err("native node has no baseline or private probe identity".into());
            };
            if pin.net.name.contains(&self.prefix) {
                return Err("private probe changed network naming".into());
            }
            let group = groups
                .entry(&pin.net.code)
                .or_insert_with(|| ConnectivityNet {
                    name: pin.net.name.clone(),
                    class: pin.net.class.clone(),
                    pins: Vec::new(),
                });
            if group.name != pin.net.name || group.class != pin.net.class {
                return Err("inconsistent native network metadata".into());
            }
            group.pins.extend(keys);
        }
        let mut projection = projected.into_values().collect::<Vec<_>>();
        for pins in &mut projection {
            pins.sort();
        }
        projection.sort();
        if projection != self.pins.connectivity()
            || seen_original.len() != baseline.len()
            || seen_probes.len() != self.probes.len()
        {
            return Err("probe changed original connectivity or omitted contacts".into());
        }
        let mut nets = groups.into_values().collect::<Vec<_>>();
        let mut coverage = BTreeSet::new();
        for net in &mut nets {
            net.pins.sort();
            for pin in &net.pins {
                if !coverage.insert(pin.clone()) {
                    return Err("source pin appears in multiple probe networks".into());
                }
            }
        }
        for pin in &self.isolated {
            if !coverage.insert(pin.clone()) {
                return Err("isolated no-connect appeared in a network".into());
            }
        }
        if coverage.len() != self.pins.pins().len() + self.pins.unexported().len() {
            return Err("incomplete source pin connectivity coverage".into());
        }
        nets.sort_by(|a, b| a.pins.cmp(&b.pins));
        Ok(PinConnectivity {
            nets,
            isolated_no_connect: self.isolated.clone(),
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{NetlistComponent, NetlistNet, NetlistNode, NetlistSheet, NetlistUnit};
    const ROOT: &str = "11111111-1111-4111-8111-111111111111";
    const REAL: &str = "22222222-2222-4222-8222-222222222222";
    const VIRTUAL: &str = "33333333-3333-4333-8333-333333333333";

    fn fixture(kind: &str) -> (ParsedSchematicProject, NetlistDocument, Vec<u8>) {
        let text = format!(
            r##"(kicad_sch (version 20260306) (generator eeschema) (uuid "{ROOT}")
          (lib_symbols
            (symbol "Test:Real" (symbol "Real_1_1" (pin passive line (at 0 0 0) (number "1") (name ""))))
            (symbol "Test:Virtual" (symbol "Virtual_1_1" (pin {kind} line (at 0 0 0) (number "1") (name "")))))
          (symbol (uuid "{REAL}") (lib_id "Test:Real") (unit 1) (at 10 10 0) (property "Reference" "U1") (property "Value" "Real") (pin "1" (uuid "44444444-4444-4444-8444-444444444444")) (instances (project "pins" (path "/{ROOT}" (reference "U1") (unit 1)))))
          (symbol (uuid "{VIRTUAL}") (lib_id "Test:Virtual") (unit 1) (at 10 10 0) (property "Reference" "#V1") (property "Value" "Virtual") (pin "1" (uuid "55555555-5555-4555-8555-555555555555")) (instances (project "pins" (path "/{ROOT}" (reference "#V1") (unit 1))))))"##
        );
        let parsed = parse_schematic("pins.kicad_sch", text.as_bytes()).unwrap();
        let revision =
            SchematicArtifactRevision::new(vec![parsed.artifact.clone()], "10.0.7", 1, false)
                .unwrap();
        let project = ParsedSchematicProject {
            root_relative_path: "pins.kicad_sch".into(),
            files: vec![parsed],
            revision,
            editor_lock_present: false,
        };
        let native = NetlistDocument {
            export_version: "E".into(),
            sheets: vec![NetlistSheet {
                number: "1".into(),
                name: "/".into(),
                uuid_path: "/".into(),
            }],
            components: vec![NetlistComponent {
                reference: "U1".into(),
                value: "Real".into(),
                footprint: None,
                symbol_uuid: Some(REAL.into()),
                sheet_path: "/".into(),
                sheet_uuid_path: "/".into(),
                library: "Test".into(),
                library_part: "Real".into(),
                units: Some(vec![NetlistUnit {
                    name: "A".into(),
                    pins: vec!["1".into()],
                }]),
            }],
            nets: vec![NetlistNet {
                code: "1".into(),
                name: "Supply".into(),
                class: Some("Default".into()),
                nodes: vec![NetlistNode {
                    reference: "U1".into(),
                    pin: "1".into(),
                    pin_function: String::new(),
                    pin_type: "passive+no_connect".into(),
                }],
            }],
        };
        (project, native, text.into_bytes())
    }
    fn plan(
        project: &ParsedSchematicProject,
        native: &NetlistDocument,
        bytes: &[u8],
    ) -> Result<PinProbePlan, String> {
        PinProbePlan::prepare(
            project,
            native,
            &BTreeMap::from([("pins.kicad_sch".into(), bytes)]),
        )
    }
    fn witness(plan: &PinProbePlan) -> NetlistDocument {
        let mut native = plan.original.clone();
        for reference in plan.probes.keys() {
            let raw = plan.candidate.files[0]
                .symbols
                .iter()
                .find(|s| &s.reference == reference)
                .unwrap();
            let (library, part) = raw.lib_id.split_once(':').unwrap();
            native.components.push(NetlistComponent {
                reference: reference.clone(),
                value: "Contact".into(),
                footprint: None,
                symbol_uuid: Some(raw.source_uuid.clone()),
                sheet_path: "/".into(),
                sheet_uuid_path: "/".into(),
                library: library.into(),
                library_part: part.into(),
                units: Some(vec![NetlistUnit {
                    name: "A".into(),
                    pins: vec!["1".into()],
                }]),
            });
            native.nets[0].nodes.push(NetlistNode {
                reference: reference.clone(),
                pin: "1".into(),
                pin_function: String::new(),
                pin_type: "passive".into(),
            });
        }
        native.nets[0].nodes[0].pin_type = "passive".into();
        native
    }

    #[test]
    fn private_insertion_binds_original_bytes_and_complete_contact_coverage() {
        let (project, native, bytes) = fixture("power_in");
        let plan = plan(&project, &native, &bytes).unwrap();
        assert_eq!(plan.probe_count(), 1);
        for original in &project.files[0].symbols {
            assert_eq!(
                plan.candidate.files[0]
                    .symbols
                    .iter()
                    .find(|s| s.source_uuid == original.source_uuid),
                Some(original)
            );
        }
        let result = plan.validate(&witness(&plan)).unwrap();
        assert_eq!(result.nets()[0].pins.len(), 2);
        assert_eq!(result.nets()[0].name, "Supply");
        assert!(result.isolated_no_connect().is_empty());
        assert!(
            plan.original.nets[0].nodes[0]
                .pin_type
                .ends_with("+no_connect")
        );
        let stale = [bytes.as_slice(), b"\n"].concat();
        assert!(
            PinProbePlan::prepare(
                &project,
                &native,
                &BTreeMap::from([("pins.kicad_sch".into(), stale.as_slice())])
            )
            .is_err()
        );
    }

    #[test]
    fn private_witness_rejects_missing_extra_and_changed_native_evidence() {
        let (project, native, bytes) = fixture("power_in");
        let plan = plan(&project, &native, &bytes).unwrap();
        let good = witness(&plan);
        for mode in 0..7 {
            let mut bad = good.clone();
            match mode {
                0 => {
                    bad.nets[0].nodes.pop();
                }
                1 => {
                    let duplicate = bad.nets[0].nodes[1].clone();
                    bad.nets[0].nodes.push(duplicate);
                }
                2 => bad.nets[0].name = "Changed".into(),
                3 => bad.nets[0].class = Some("Changed".into()),
                4 => bad.nets[0].nodes[1].pin_type = "power_in".into(),
                5 => bad.components[0].units.as_mut().unwrap()[0].name = "Different".into(),
                6 => {
                    let node = bad.nets[0].nodes.pop().unwrap();
                    bad.nets.push(NetlistNet {
                        code: "2".into(),
                        name: plan.prefix.clone(),
                        class: None,
                        nodes: vec![node],
                    });
                }
                _ => unreachable!(),
            }
            assert!(plan.validate(&bad).is_err(), "mode {mode}");
        }
    }

    #[test]
    fn electrical_no_connect_is_separate_from_probe_and_marker_evidence() {
        let (project, native, bytes) = fixture("no_connect");
        let plan = plan(&project, &native, &bytes).unwrap();
        assert_eq!(plan.probe_count(), 0);
        assert_eq!(plan.files()["pins.kicad_sch"], bytes);
        let result = plan.validate(&native).unwrap();
        assert_eq!(result.isolated_no_connect().len(), 1);
        assert_eq!(result.nets()[0].pins.len(), 1);
    }
}
